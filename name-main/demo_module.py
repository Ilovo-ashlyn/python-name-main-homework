"""正确写法示例：这个文件既能被直接运行，也能被别的模块安全导入。

运行方式一：python demo_module.py
运行方式二：python import_demo.py（本文件被导入）
"""


# 顶层代码：无论「直接运行」还是「被导入」都会执行
print(f"[顶层] demo_module.__name__ = {__name__!r}")


def greet(name: str) -> str:
    """供其他模块复用的普通函数。"""
    return f"Hello, {name}!"


def main() -> None:
    """只在「作为程序入口」时才该执行的逻辑。"""
    print("[main()] 程序入口开始执行")
    print(greet("Python"))
    print("[main()] 程序入口执行结束")


# ---------------------------------------------------------------------------
# 本题主角：运行方式开关
# ---------------------------------------------------------------------------
if __name__ == '__main__':
    print("[保护块] 我是被直接运行的，__name__ 是 '__main__'，所以调用 main()")
    main()
else:
    # 实际项目里通常不写 else，这里为了教学把「否则」显式展示出来
    print(f"[保护块] 我是被导入的，__name__ 是 {__name__!r}，不调用 main()")
